// npm run extract — regenerates src/content/*.ts from the constants in src/main.js.
// While main.js is still the live game, balance changes go into main.js and this script copies them over;
// test/content.test.ts fails when the two drift apart. Once the engine replaces main.js, src/content becomes the
// source of truth and this script is deleted.
import { writeFileSync } from 'node:fs';
import { mainSource, readConst } from './main-source.ts';

/** Which main.js constants go into which content file. */
export const GROUPS: Record<string, string[]> = {
  maps: ['MAPS', 'LIQ'], // LIQ: liquid looks; the engine reads only each kind's ground height
  enemies: ['ED', 'GROUPING', 'ATK', 'ATKX'],
  towers: ['TT', 'DTYPE', 'DNAME', 'SPEC', 'UPC', 'MORTAR_DEAD'], // RANKX is tooltip text: it moves with the UI
  barracks: ['BARR', 'SOL_INFO', 'SOL_REGEN', 'SOL_FIRST', 'SOL_LAST', 'DRUM'],
  spells: ['SPELLS', 'MILITIA'],
  campaign: ['AREAS', 'LEVELS', 'UNLOCKS', 'DIFFS', 'BOUNTY'],
  skills: ['SK', 'SK_STAT', 'SK_WHEN'],
  ai: ['WANT'],
};

/** Reads one constant; UNLOCKS refers to TYPES, which is just the tower keys. */
export function readGameConst(src: string, name: string): unknown {
  const scope = name === 'UNLOCKS' ? { TYPES: Object.keys(readConst<object>(src, 'TT')) } : {};
  return readConst(src, name, scope);
}

/** Parameter types for the one-argument functions found in content, by the key that holds them. */
const PARAM: Record<string, string> = {
  st: '{ dmg: number; range: number; rate: number; dps: number }', // SPEC: specialisation stats from the level-3 stats
  c: 'number', // MAPS liquid: river or lava centre line along one axis
};

/** Serialises a value as TypeScript source. Functions keep their source text (RANKX formulas, map liquid curves). */
export function toSource(v: unknown, ind = ''): string {
  const next = ind + '  ';
  if (typeof v === 'function') return v.toString();
  if (Array.isArray(v)) {
    const flat = v.every(x => x === null || typeof x !== 'object');
    if (flat) return `[${v.map(x => toSource(x)).join(', ')}]`;
    return `[\n${v.map(x => next + toSource(x, next)).join(',\n')},\n${ind}]`;
  }
  if (v && typeof v === 'object') {
    const keys = Object.keys(v);
    if (!keys.length) return '{}';
    const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k));
    const val = (k: string, x: unknown) => {
      if (k === 'col' && typeof x === 'number') return '0x' + x.toString(16).padStart(6, '0');
      if (typeof x === 'function' && PARAM[k]) return x.toString().replace(/^(\w+) =>/, `($1: ${PARAM[k]}) =>`);
      return toSource(x, next);
    };
    return `{\n${keys.map(k => `${next}${key(k)}: ${val(k, (v as Record<string, unknown>)[k])}`).join(',\n')},\n${ind}}`;
  }
  return JSON.stringify(v);
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop()!)) {
  const src = mainSource();
  for (const [file, names] of Object.entries(GROUPS)) {
    const body = names.map(n => `export const ${n} = ${toSource(readGameConst(src, n))};\n`).join('\n');
    const out = `// Generated by \`npm run extract\` from src/main.js. Do not edit by hand while main.js is the live game.\n\n${body}`;
    writeFileSync(new URL(`../src/content/${file}.ts`, import.meta.url), out);
    console.log(`src/content/${file}.ts: ${names.join(', ')}`);
  }
}
